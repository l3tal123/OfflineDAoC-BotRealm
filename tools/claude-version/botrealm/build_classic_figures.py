"""Writes GameServer/mode165/ClassicFigures165.cs from the client's fig3tofigmain.csv (race, gender, face, hair style ->
classic figure model). In BotRealm the profile uses classic figures, where every face + hair style is its own model,
so the hiring window's preview figure shows the chosen face and hair by model alone (tested in the original client, 2026-10-30).
"""
import collections, csv, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, "..", "..", ".."))
SRC = os.path.join(os.path.dirname(ROOT), "Claude Takeover GitHub", "OfflineDAoC", "source", "tools",
                   "observer-model-inspection", "fig3tofigmain.csv")
OUT = os.path.join(ROOT, "development-source", "server", "GameServer", "mode165", "ClassicFigures165.cs")
RACES = ["Briton", "Avalonian", "Highlander", "Saracen", "Norseman", "Troll", "Dwarf", "Kobold", "Celt", "Firbolg", "Elf",
         "Lurikeen", "Inconnu", "Valkyn", "Sylvan", "HalfOgre", "Frostalf", "Shar"]

table = collections.defaultdict(dict)
for r in csv.reader(open(SRC, encoding="latin1")):
    if len(r) >= 6 and r[1].strip().isdigit():
        race, gender, face, hair, model = (int(x) for x in r[1:6])
        if race < len(RACES):
            table[(race, gender)][(face, hair)] = model
# The hiring window's LOOK picker (owner 2026-10-30: "merge the buttons into one option"): the looks a PLAYER could pick
# at character creation, from the client's figtofig3main.csv rows "<RACE> <MALE|FEMALE> n" (n = 1..12), column 2 = the
# classic player model, in n order, each model once (Firbolg male and Valkyn female repeat one). Not every monsters.csv
# row on the figure: those include NPC-only variants that drew as black figures (owner, 2026-10-30).
PLAYER_LOOKS = os.path.join(os.path.dirname(SRC), "figtofig3main.csv")
by_name = {}
for r in csv.reader(open(PLAYER_LOOKS, encoding="latin1")):
    parts = r[0].strip().rsplit(" ", 2) if r else []
    if len(parts) == 3 and parts[2].isdigit() and parts[1] in ("MALE", "FEMALE") and len(r) > 1 and r[1].strip().isdigit():
        by_name.setdefault((parts[0], parts[1] == "FEMALE"), {}).setdefault(int(parts[2]), int(r[1]))
look_lines = []
for (race, gender), cells in sorted(table.items()):
    key = (RACES[race].upper().replace("HALFOGRE", "HALF_OGRE"), bool(gender))
    looks = []
    for n in sorted(by_name.get(key, {})):
        if by_name[key][n] not in looks:
            looks.append(by_name[key][n])
    if not looks:
        sys.exit(f"no player looks for {key}")
    look_lines.append(f"            [(eRace.{RACES[race]}, {'true' if gender else 'false'})] = [{', '.join(map(str, looks))}],")

# Hair colours (owner 2026-10-30): each look's hair set is its monsters.csv row's column 19; the colours of a set are
# the period client's hair.csv row (research/period-data/client-1.64/gamedata), distinct textures in column order
# (Trolls repeat four, so 4). The hire window's colour index i is the i-th of them; the clients re-skin the hair.
MON = os.path.join(os.path.dirname(SRC), "monsters.csv")
mon = {}
for r in csv.reader(open(MON, encoding="latin1")):
    if r and r[0].strip().isdigit() and len(r) > 20:
        mon[int(r[0])] = r
HAIR = os.path.join(ROOT, "development-source", "research", "period-data", "client-1.64", "gamedata", "hair.csv")
hair_sets = {}
for r in csv.reader(open(HAIR, encoding="latin1")):
    if r and r[0].strip().isdigit():
        colours = []
        for c in r[2:10]:
            if c.strip().isdigit() and int(c) not in colours:
                colours.append(int(c))
        hair_sets[int(r[0])] = colours
hair_counts = {}
for line in look_lines:
    for m in line.split("= [")[1].rstrip("],").split(","):
        m = int(m)
        hs = int(mon[m][19]) if m in mon and mon[m][19].strip().isdigit() else 0
        hair_counts[m] = len(hair_sets.get(hs, []))
hair_lines = ", ".join(f"[{m}] = {n}" for m, n in sorted(hair_counts.items()) if n > 1)

lines = []
for (race, gender), cells in sorted(table.items()):
    # only the faces and hair styles the client has (Firbolg female skips a face number): list them in order
    faces = sorted({f for f, _ in cells})
    hairs = sorted({h for _, h in cells})
    grid = ", ".join("[" + ", ".join(str(cells.get((f, h), 0)) for h in hairs) + "]" for f in faces)
    lines.append(f"            [(eRace.{RACES[race]}, {'true' if gender else 'false'})] = [{grid}],")
cs = """// Generated by tools/claude-version/botrealm/build_classic_figures.py from the client's fig3tofigmain.csv. Do not edit.
using System.Collections.Generic;

namespace DOL.GS
{
    /// <summary>Classic figure models by race, sex, face and hair style (BotRealm's hiring preview).</summary>
    public static class ClassicFigures165
    {
        // (race, female) -> models[face][hair style], by position among the faces and styles the client has
        private static readonly Dictionary<(eRace, bool), ushort[][]> Table = new()
        {
%s
        };

        // (race, female) -> the classic looks a player could pick (figtofig3main.csv), in the client's order: the hiring window's LOOK picker
        private static readonly Dictionary<(eRace, bool), ushort[]> Looks = new()
        {
%s
        };

        // look model -> how many hair colours its hair set has (monsters.csv col 19 -> period hair.csv; absent = none)
        private static readonly Dictionary<ushort, int> HairColours = new() { %s };

        /// <summary>The hair colours this look can have (0 or 1 = no choice).</summary>
        public static int HairColourCount(ushort model) => HairColours.TryGetValue(model, out int n) ? n : 0;

        public static int LookCount(eRace race, bool female) => Looks.TryGetValue((race, female), out ushort[] l) ? l.Length : 0;

        /// <summary>The model of look n (0-based) of this race and sex, or 0 when there is none.</summary>
        public static ushort LookModel(eRace race, bool female, int look) =>
            Looks.TryGetValue((race, female), out ushort[] l) && look >= 0 && look < l.Length ? l[look] : (ushort)0;

        public static int Faces(eRace race, bool female) => Table.TryGetValue((race, female), out ushort[][] g) ? g.Length : 0;

        public static int Hairs(eRace race, bool female) => Table.TryGetValue((race, female), out ushort[][] g) && g.Length > 0 ? g[0].Length : 0;

        /// <summary>The classic model for this look, or 0 when the client has none.</summary>
        public static ushort Model(eRace race, bool female, int face, int hair) =>
            Table.TryGetValue((race, female), out ushort[][] g) && face >= 0 && face < g.Length && hair >= 0 && hair < g[face].Length
                ? g[face][hair] : (ushort)0;
    }
}
""" % ("\n".join(lines), "\n".join(look_lines), hair_lines)
open(OUT, "w", encoding="utf-8", newline="\r\n").write(cs)
print(f"{OUT}: {len(lines)} race/sex rows")
